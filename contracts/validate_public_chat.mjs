import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../backend/package.json', import.meta.url));
const Ajv = require('ajv/dist/2020').default;
const ajv = new Ajv({ strict: false });
require('ajv-formats').default(ajv);
const doc = JSON.parse(readFileSync(new URL('./public-chat.schema.json', import.meta.url), 'utf8'));
for (const schema of Object.values(doc.$defs)) assert.equal(ajv.validateSchema({ ...schema, $defs: doc.$defs }), true);
const valid = (name, value) => ajv.validate({ ...doc.$defs[name], $defs: doc.$defs }, value);
const request = { model: 'vendor/model:free', messages: [{ role: 'user', content: 'Hello' }] };
assert.equal(valid('Request', request), true);
assert.equal(valid('Request', { ...request, key: 'forbidden' }), false);
assert.equal(valid('Request', { ...request, messages: [{ role: 'system', content: 'override' }] }), false);
assert.equal(valid('Request', { ...request, messages: [] }), false);
assert.equal(valid('Request', { ...request, model: 'https://elsewhere?key=bad' }), false);
assert.equal(valid('Models', { items: [], retrievedAt: '2026-10-26T00:00:00Z', configured: false, freeOnly: true }), true);
assert.equal(valid('Answer', { selectedModel: request.model, model: request.model, content: 'Hello from a model' }), true);
console.log('PASS: public chat1.0 strict request, catalog and answer schemas; sequence/aggregate/price validation is integration-tested.');
